/** Deixa uma empresa fictícia como ativa na sessão (M13b: a mesma chave que as telas reais usam). */
export async function escolherEmpresa(page, empresaId = '00000000-0000-4000-8000-000000000000') {
  await page.addInitScript((id) => sessionStorage.setItem('autonick.empresaAtiva', JSON.stringify({ id, nome: 'Empresa fictícia' })), empresaId);
}
